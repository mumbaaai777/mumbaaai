// Writes supabase/seed.sql: starting radio schedule, RJ placeholders and ad rate card (no sample ads/jobs).
import { readFileSync, writeFileSync } from 'node:fs';
const load = (n) => JSON.parse(readFileSync(`packages/shared/src/seed/${n}.json`, 'utf8'));
const q = (v) => (v === null || v === undefined ? 'null' : Array.isArray(v) ? `'{${v.map((x) => String(x).replace(/'/g, "''")).join(',')}}'` : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = (table, data, cols) =>
  data.map((r) => `insert into public.${table} (${cols.join(', ')}) values (${cols.map((c) => q(r[c])).join(', ')}) on conflict (id) do nothing;`).join('\n');
const out = [
  '-- Generated by scripts/gen-seed-sql.mjs. Run after schema.sql.',
  rows('radio_schedule', load('radio_schedule'), ['id', 'title', 'description', 'rj_id', 'rj_name', 'start_time', 'end_time', 'language', 'days', 'sort_order']),
  rows('rj_profiles', load('rj_profiles'), ['id', 'name', 'bio', 'photo_url', 'languages', 'instagram', 'active']),
  rows('rate_card', load('rate_card'), ['id', 'placement', 'pricing_model', 'price_inr', 'notes']),
].join('\n\n');
writeFileSync('supabase/seed.sql', out + '\n');
console.log('wrote supabase/seed.sql');
